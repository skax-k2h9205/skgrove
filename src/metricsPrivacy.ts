/**
 * 파트 지표 공개 기준.
 *
 * 인원이 적은 파트에서는 집계 자체가 신원 추정 단서가 된다. 3명짜리 파트의
 * "접수 2건"은 누가 냈는지 좁혀준다. 익명 설문 도구들이 공통으로 쓰는 방식대로
 * 미달 파트는 값을 흐리는 대신 아예 표시하지 않는다. 흐린 값도 단서가 되기 때문이다.
 *
 * 이 상수는 지표 화면과 접수 화면이 함께 쓴다. 접수자에게 **응답하기 전에**
 * 기준을 알려야 의미가 있어서, 두 화면이 같은 값을 가리켜야 한다.
 */
export const MIN_MEMBERS_TO_REVEAL = 5;

/** 지표를 공개해도 되는 파트인지. 리더 권한과 무관하다 — 권한이 아니라 익명성 문제다. */
export function isRevealable(part: { members: number }) {
  return part.members >= MIN_MEMBERS_TO_REVEAL;
}

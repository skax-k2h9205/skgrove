// 상담 파이프라인의 위기 triage. LLM 을 쓰지 않는 정규식/키워드 게이트다(0 콜, 즉시).
// 미탐(진짜 위기를 놓침)이 오탐보다 위험하므로, 애매하면 감지하는 쪽으로 기운다.
// 대신 명백한 부정문("죽고 싶지 않")과 강조 관용구("배고파 죽겠다")만 배제한다.
// 정교한 분류(상담/룰/잡담 라우팅)는 후속(Phase 2)의 LLM 라우터로.

/** 위기로 볼 표현들. */
const CRISIS = [
  /자살/, /죽고\s*싶/, /죽어\s*버리/, /목숨을?\s*끊/, /자해/, /손목을?\s*긋/,
  /뛰어내리/, /살고\s*싶지\s*않/, /사라지고\s*싶/, /없어지고\s*싶/, /다\s*끝내고\s*싶/,
  /죽여\s*버리/, /해치고\s*싶/,
];

/** 위기 패턴과 겹쳐 보여도 위기가 아닌 것들(부정문 등). 그 구절만 마스킹한다. */
const NEGATION = [/죽고\s*싶지\s*않/g, /죽고\s*싶진\s*않/g, /죽고\s*싶은\s*건\s*아니/g];

/**
 * 자·타해 위기 신호 여부. 순수함수.
 * @param {string} text
 * @returns {boolean}
 */
export function detectCrisis(text) {
  if (!text || typeof text !== 'string') return false;
  let t = text.replace(/\s+/g, ' ');
  // 부정문("죽고 싶지 않")은 그 구절만 지운다 — 같은 메시지의 다른 위기 신호(예: "자해")는
  // 여전히 감지되어야 한다(미탐이 오탐보다 위험).
  for (const r of NEGATION) t = t.replace(r, ' ');
  return CRISIS.some((r) => r.test(t));
}

